import { chromium } from '../../admin/node_modules/.cache/tv5-tools/node_modules/playwright/index.mjs';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
const root = new URL('../../',import.meta.url);
const webBase = process.env.TV5_WEB_URL ?? 'http://localhost:3000';
const apiBase = process.env.TV5_API_URL ?? 'http://localhost:8080/api/v1';
const output = new URL('artifacts/tv5-week3/',root); await fs.mkdir(output,{recursive:true});
const users = JSON.parse(await fs.readFile(new URL('mobile/node_modules/.cache/tv5-week3-session.json',root),'utf8'));
const checks = [], errors = [], created = [];
let succeeded = false;
const browser = await chromium.launch({ executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true,args:['--use-angle=swiftshader','--enable-unsafe-swiftshader','--enable-webgl'] });
const context = await browser.newContext({viewport:{width:1440,height:1000}});
const page = await context.newPage(); page.setDefaultNavigationTimeout(120000); page.setDefaultTimeout(45000); page.on('pageerror',error=>errors.push(error.message));
const check=(name,condition)=>{assert.ok(condition,name);checks.push({name,status:'passed'});};
try {
  await page.goto(`${webBase}/map`,{waitUntil:'domcontentloaded',timeout:120000});
  await page.getByLabel('Tìm điểm đến',{exact:true}).waitFor({timeout:90000});
  await page.locator('[data-destination-id]').first().waitFor({timeout:90000});
  await page.waitForFunction(()=>!document.body.innerText.includes('Đang tải bản đồ…'),{},{timeout:40000});
  check('MapLibre canvas exists',await page.locator('.maplibregl-canvas').count()===1);
  check('actual street map loaded',!await page.getByText('Chưa tải được bản đồ',{exact:true}).count());
  check('map attribution',await page.locator('.maplibregl-ctrl-attrib').innerText().then(t=>t.includes('OpenStreetMap')&&t.includes('OpenFreeMap')));
  await page.screenshot({path:new URL('web-map.png',output).pathname.replace(/^\/([A-Z]:)/,'$1'),fullPage:true});
  const destinations=await fetch(`${apiBase}/destinations?size=20`).then(r=>r.json());
  const destination=destinations.items.find(d=>typeof d.latitude==='number'&&typeof d.longitude==='number');
  await page.goto(`${webBase}/destination/${destination.id}`,{waitUntil:'domcontentloaded'});
  await page.getByRole('heading',{name:destination.name,exact:true}).waitFor();
  await page.getByRole('link',{name:'Chỉ đường',exact:true}).click();
  await page.getByLabel('Điểm đến',{exact:true}).waitFor();
  await page.waitForFunction((id)=>document.querySelector('select[aria-label="Điểm đến"]')?.value===id,destination.id);
  check('detail opens correct route destination',await page.getByLabel('Điểm đến',{exact:true}).inputValue()===destination.id);
  await page.getByLabel('Điểm xuất phát',{exact:true}).selectOption(destinations.items.find(d=>d.id!==destination.id&&typeof d.latitude==='number')?.id);
  await page.getByRole('button',{name:'Tính tuyến đường',exact:true}).click();
  await page.getByRole('alert').filter({hasText:'chưa được cấu hình'}).waitFor({timeout:30000});
  check('missing ORS key handled without fake route',true);
  await page.screenshot({path:new URL('web-route.png',output).pathname.replace(/^\/([A-Z]:)/,'$1'),fullPage:true});
  await page.goto(`${webBase}/community`,{waitUntil:'domcontentloaded'});
  await page.getByRole('link',{name:/Đăng nhập để đăng bài/}).waitFor(); check('guest reads feed and sees existing login link',true);
  await context.addInitScript(({token,user})=>{localStorage.setItem('vista_token',token);localStorage.setItem('vista_user',JSON.stringify(user));},{token:users[0].accessToken,user:users[0]});
  await page.reload(); await page.getByLabel('Nội dung bài đăng',{exact:true}).waitFor();
  const draft=`TV5 browser QA ${Date.now()}`;
  await page.getByLabel('Nội dung bài đăng',{exact:true}).fill(draft);
  const png=await page.evaluate(()=>{const c=document.createElement('canvas');c.width=2;c.height=2;const g=c.getContext('2d');g.fillStyle='#0984e3';g.fillRect(0,0,2,2);return c.toDataURL('image/png').split(',')[1];});
  await page.locator('input[type=file]').setInputFiles({name:'qa.png',mimeType:'image/png',buffer:Buffer.from(png,'base64')});
  await page.getByRole('button',{name:'Đăng bài',exact:true}).click();
  await page.getByRole('alert').waitFor({timeout:30000});
  check('unconfigured real Storage returns error and retains draft',await page.getByLabel('Nội dung bài đăng',{exact:true}).inputValue()===draft);
  await page.getByRole('button',{name:'Bỏ ảnh 1',exact:true}).click();
  const postResponse=page.waitForResponse(r=>r.url().endsWith('/api/v1/posts')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Đăng bài',exact:true}).click();
  const response=await postResponse; const post=await response.json(); created.push(post.id); check('web creates real persisted post',response.status()===201);
  await page.getByText(draft,{exact:true}).waitFor(); await page.reload(); await page.getByText(draft,{exact:true}).waitFor(); check('post survives browser reload',true);
  const article=page.locator('article').filter({hasText:draft});
  await article.getByRole('button',{name:'Sửa bài',exact:true}).click(); await article.getByLabel('Sửa nội dung bài đăng').fill(draft+' edited'); await article.getByRole('button',{name:'Lưu thay đổi',exact:true}).click();
  await page.getByText(draft+' edited',{exact:true}).waitFor(); check('web edits persisted post',true);
  await article.getByRole('button',{name:'Xem bình luận',exact:true}).click(); await article.getByLabel('Nội dung bình luận',{exact:true}).fill('QA browser comment'); await article.getByRole('button',{name:'Lưu bình luận',exact:true}).click();
  await article.getByText('QA browser comment',{exact:true}).waitFor(); check('web creates real comment',true);
  await page.screenshot({path:new URL('web-community.png',output).pathname.replace(/^\/([A-Z]:)/,'$1'),fullPage:true});
  check('no uncaught browser errors',errors.length===0);
  succeeded = true;
} finally {
  for(const id of created)await fetch(`${apiBase}/posts/${id}`,{method:'DELETE',headers:{Authorization:`Bearer ${users[0].accessToken}`}}).catch(()=>{});
  await fs.writeFile(new URL('web-verification.json',output),JSON.stringify({status:succeeded?'passed':'failed',date:new Date().toISOString(),checks,errors},null,2)); await browser.close(); console.log(JSON.stringify({checks,errors},null,2));
}
